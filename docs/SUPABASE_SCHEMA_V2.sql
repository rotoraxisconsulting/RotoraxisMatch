-- ============================================================
-- BASE TABLES
-- ============================================================

-- profiles
-- Bridge between auth.users and app-level roles.
-- One row per authenticated user. id = auth.users.id.
CREATE TABLE profiles (
  id         UUID         PRIMARY KEY, -- = auth.users.id
  role       app_role     NOT NULL,    -- SERVER-ASSIGNED: set by auth trigger on registration; admin-only after
  status     user_status  NOT NULL DEFAULT 'pending_verification', -- SERVER-MANAGED: set by admin; not user-editable
  created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Canonical location catalog used by technicians, companies and offers.
-- MVP seed is curated, not a complete worldwide airport database.
-- Add new airport rows later without changing schema.
CREATE TABLE location_airports (
  id           TEXT             PRIMARY KEY, -- e.g. airport:LEVC
  country_name TEXT             NOT NULL,
  city         TEXT             NOT NULL,
  airport      TEXT             NOT NULL,
  icao         TEXT             NOT NULL UNIQUE,
  iata         TEXT,
  latitude     DOUBLE PRECISION NOT NULL,
  longitude    DOUBLE PRECISION NOT NULL,
  is_active    BOOLEAN          NOT NULL DEFAULT true
);


-- ============================================================
-- TECHNICIAN TABLES
-- ============================================================

-- IMPORTANT: Companies must NEVER query technician_profiles directly.
-- All company-facing technician queries must go through technician_public_view (defined in RLS_PLAN_V2.md).
-- The view enforces column-level privacy via CASE WHEN offer_accepted_between().
CREATE TABLE technician_profiles (
  id                   UUID                PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id              UUID                NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  anonymous_code       TEXT                NOT NULL UNIQUE,

  -- Private fields (hidden until offer accepted)
  first_name           TEXT                NOT NULL,
  last_name            TEXT                NOT NULL,
  email                TEXT                NOT NULL,
  phone                TEXT,
  birth_date           DATE                NOT NULL,

  -- Public professional fields
  technician_type      TEXT                NOT NULL REFERENCES technician_types(code),
  location_city_id     TEXT                NOT NULL REFERENCES location_airports(id),

  -- Availability as JSONB: { immediately, available_from, contract_types[] }
  availability         JSONB               NOT NULL DEFAULT '{"immediately": false, "available_from": null, "contract_types": []}',

  -- Status — verification_status is ADMIN-ONLY; technician cannot write this field
  verification_status  verification_status NOT NULL DEFAULT 'pending',
  profile_completeness INT                 NOT NULL DEFAULT 0 CHECK (profile_completeness BETWEEN 0 AND 100),

  -- Optional private fields
  social_links         JSONB,

  created_at           TIMESTAMPTZ         NOT NULL DEFAULT now(),
  updated_at           TIMESTAMPTZ         NOT NULL DEFAULT now()
);

CREATE TABLE technician_licenses (
  id             UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  technician_id  UUID        NOT NULL REFERENCES technician_profiles(id) ON DELETE CASCADE,
  license_code   TEXT        NOT NULL REFERENCES license_categories(code),
  issued_at      DATE,
  expires_at     DATE,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (technician_id, license_code)
);

CREATE TABLE technician_habilitations (
  id                  UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  technician_id       UUID        NOT NULL REFERENCES technician_profiles(id) ON DELETE CASCADE,
  license_code        TEXT        NOT NULL REFERENCES license_categories(code),
  aircraft_type_code  TEXT        NOT NULL REFERENCES aircraft_types(code),
  issued_at           DATE,
  expires_at          DATE,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (technician_id, license_code, aircraft_type_code)
);

CREATE TABLE technician_aircraft_experience (
  id                  UUID             PRIMARY KEY DEFAULT gen_random_uuid(),
  technician_id       UUID             NOT NULL REFERENCES technician_profiles(id) ON DELETE CASCADE,
  -- aircraft_type_code must reference aircraft_types.code. No generic/fallback codes (e.g. 'GENERAL') allowed.
  aircraft_type_code  TEXT             NOT NULL REFERENCES aircraft_types(code),
  value               DOUBLE PRECISION NOT NULL CHECK (value >= 0),
  unit                experience_unit  NOT NULL,
  created_at          TIMESTAMPTZ      NOT NULL DEFAULT now(),
  UNIQUE (technician_id, aircraft_type_code)
);

-- MVP review model: admin manually sets status. No audit log, no auto-expiration, no reviewer id.
-- Add reviewed_by / audit table / cron trigger later only if real users need them.
CREATE TABLE documents (
  id               UUID             PRIMARY KEY DEFAULT gen_random_uuid(),
  technician_id    UUID             NOT NULL REFERENCES technician_profiles(id) ON DELETE CASCADE,
  type             TEXT             NOT NULL,  -- 'license' | 'medical' | 'id' | 'training' | 'resume' | 'other'
  file_name        TEXT             NOT NULL,
  storage_path     TEXT             NOT NULL,  -- local path in demo; Supabase Storage path later
  status           document_status  NOT NULL DEFAULT 'pending',
  uploaded_at      TIMESTAMPTZ      NOT NULL DEFAULT now(),
  reviewed_at      TIMESTAMPTZ,                -- set when admin changes status; cleared on reset to pending
  rejection_reason TEXT,                       -- set when rejected; cleared on all other transitions
  expires_at       TIMESTAMPTZ                 -- for licenses and time-limited certificates
);


-- ============================================================
-- COMPANY TABLES
-- ============================================================

CREATE TABLE companies (
  id                  UUID                PRIMARY KEY DEFAULT gen_random_uuid(),
  name                TEXT                NOT NULL,
  location_city_id    TEXT                NOT NULL REFERENCES location_airports(id),
  phone               TEXT,
  email               TEXT                NOT NULL,
  company_type        TEXT                NOT NULL REFERENCES company_types(code),
  verification_status verification_status NOT NULL DEFAULT 'pending', -- ADMIN-ONLY; company cannot write this
  created_at          TIMESTAMPTZ         NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ         NOT NULL DEFAULT now()
);

-- Company members are created manually in the MVP.
-- No self-service invitations, invite tokens, or email invite flows.
CREATE TABLE company_members (
  id          UUID                PRIMARY KEY DEFAULT gen_random_uuid(),
  company_id  UUID                NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  user_id     UUID                NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  role        company_member_role NOT NULL DEFAULT 'viewer',
  created_at  TIMESTAMPTZ         NOT NULL DEFAULT now(),
  UNIQUE (company_id, user_id),
  -- MVP: one company per company user. Multi-company membership is future scope.
  UNIQUE (user_id)
);


-- ============================================================
-- OFFERS
-- ============================================================

CREATE TABLE offers (
  id                    UUID          PRIMARY KEY DEFAULT gen_random_uuid(),
  company_id            UUID          NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  title                 TEXT          NOT NULL,
  description           TEXT          NOT NULL,
  contract_type         TEXT          NOT NULL REFERENCES contract_types(code),
  location_city_id      TEXT          NOT NULL REFERENCES location_airports(id),
  -- Controlled snapshot copied from location_airports on create/update.
  location_country      TEXT          NOT NULL,
  location_city         TEXT          NOT NULL,
  location_base_airport TEXT          NOT NULL,
  min_years_experience  INT           NOT NULL DEFAULT 0 CHECK (min_years_experience >= 0),
  status                offer_status  NOT NULL DEFAULT 'draft',
  visible               BOOLEAN       NOT NULL DEFAULT false,
  expires_at            TIMESTAMPTZ,
  created_at            TIMESTAMPTZ   NOT NULL DEFAULT now(),
  updated_at            TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- Required technician types for an offer (optional — no rows = any type accepted)
-- Composite PK (offer_id, technician_type_code) — no surrogate id column.
-- Local demo seeds include a local `id` field (e.g. "ort-001") for demo readability only.
-- Drop the local id field when inserting into Supabase; use (offer_id, technician_type_code) pairs.
CREATE TABLE offer_required_technician_types (
  offer_id             UUID NOT NULL REFERENCES offers(id) ON DELETE CASCADE,
  technician_type_code TEXT NOT NULL REFERENCES technician_types(code),
  PRIMARY KEY (offer_id, technician_type_code)
);

-- Required licenses for an offer (optional)
-- Composite PK (offer_id, license_code) — no surrogate id column.
-- Local demo seeds include a local `id` field for demo readability only.
CREATE TABLE offer_required_licenses (
  offer_id     UUID NOT NULL REFERENCES offers(id) ON DELETE CASCADE,
  license_code TEXT NOT NULL REFERENCES license_categories(code),
  PRIMARY KEY (offer_id, license_code)
);

-- Required aircraft types for an offer (optional)
-- Composite PK (offer_id, aircraft_type_code) — no surrogate id column.
-- Local demo seeds include a local `id` field for demo readability only.
CREATE TABLE offer_required_aircraft_types (
  offer_id            UUID NOT NULL REFERENCES offers(id) ON DELETE CASCADE,
  aircraft_type_code  TEXT NOT NULL REFERENCES aircraft_types(code),
  PRIMARY KEY (offer_id, aircraft_type_code)
);


-- ============================================================
-- OFFER REQUESTS
-- Company sends a direct offer to a specific technician.
-- ============================================================

CREATE TABLE offer_requests (
  id                  UUID                 PRIMARY KEY DEFAULT gen_random_uuid(),
  company_id          UUID                 NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  technician_id       UUID                 NOT NULL REFERENCES technician_profiles(id) ON DELETE CASCADE,
  offer_id            UUID                 REFERENCES offers(id) ON DELETE SET NULL,
  status              offer_request_status NOT NULL DEFAULT 'pending',
  -- READ-ONLY: set exclusively by handle_offer_accepted trigger, never by client
  identity_revealed   BOOLEAN              NOT NULL DEFAULT false,
  -- READ-ONLY: set exclusively by handle_offer_accepted trigger, never by client
  documents_unlocked  BOOLEAN              NOT NULL DEFAULT false,
  message             TEXT,
  created_at          TIMESTAMPTZ          NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ          NOT NULL DEFAULT now()
);


-- ============================================================
-- OFFER APPLICATIONS
-- Technician applies to a published offer.
-- ============================================================

CREATE TABLE offer_applications (
  id                  UUID                 PRIMARY KEY DEFAULT gen_random_uuid(),
  technician_id       UUID                 NOT NULL REFERENCES technician_profiles(id) ON DELETE CASCADE,
  offer_id            UUID                 NOT NULL REFERENCES offers(id) ON DELETE CASCADE,
  company_id          UUID                 NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  status              offer_request_status NOT NULL DEFAULT 'pending',
  -- READ-ONLY: set exclusively by handle_offer_accepted trigger, never by client
  identity_revealed   BOOLEAN              NOT NULL DEFAULT false,
  -- READ-ONLY: set exclusively by handle_offer_accepted trigger, never by client
  documents_unlocked  BOOLEAN              NOT NULL DEFAULT false,
  cover_note          TEXT,
  created_at          TIMESTAMPTZ          NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ          NOT NULL DEFAULT now(),
  -- One application per technician per offer, regardless of status.
  -- Reapplication (after withdrawn/rejected/expired) is out of scope for MVP.
  UNIQUE (technician_id, offer_id)
);


-- ============================================================
-- CHAT
-- Chat rooms are created only on acceptance.
-- ============================================================

CREATE TABLE chat_rooms (
  id                    UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  offer_request_id      UUID        REFERENCES offer_requests(id) ON DELETE CASCADE,
  offer_application_id  UUID        REFERENCES offer_applications(id) ON DELETE CASCADE,
  technician_id         UUID        NOT NULL REFERENCES technician_profiles(id) ON DELETE CASCADE,
  company_id            UUID        NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- Exactly one source must be set
  CONSTRAINT check_single_source CHECK (
    (offer_request_id IS NOT NULL AND offer_application_id IS NULL) OR
    (offer_request_id IS NULL AND offer_application_id IS NOT NULL)
  )
);

-- Enforce one chat room per offer_request (NULLs excluded)
CREATE UNIQUE INDEX idx_chat_rooms_offer_request
  ON chat_rooms(offer_request_id)
  WHERE offer_request_id IS NOT NULL;

-- Enforce one chat room per offer_application (NULLs excluded)
CREATE UNIQUE INDEX idx_chat_rooms_offer_application
  ON chat_rooms(offer_application_id)
  WHERE offer_application_id IS NOT NULL;

CREATE TABLE chat_messages (
  id                       UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  chat_room_id             UUID        NOT NULL REFERENCES chat_rooms(id) ON DELETE CASCADE,
  sender_user_id           UUID        NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  sender_company_member_id UUID        REFERENCES company_members(id) ON DELETE SET NULL,
  sender_role              sender_role NOT NULL,
  body                     TEXT        NOT NULL,
  sent_at                  TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT chat_messages_company_member_role CHECK (
    sender_company_member_id IS NULL OR sender_role = 'company'
  )
);


-- ============================================================
-- ACTIVITY / NOTIFICATION TABLES
-- ============================================================

CREATE TABLE activity_events (
  id                       UUID                      PRIMARY KEY DEFAULT gen_random_uuid(),
  type                     activity_type             NOT NULL,
  recipient_scope          activity_recipient_scope  NOT NULL,
  recipient_technician_id  UUID                      REFERENCES technician_profiles(id) ON DELETE CASCADE,
  recipient_company_id     UUID                      REFERENCES companies(id) ON DELETE CASCADE,
  actor_profile_id         UUID                      REFERENCES profiles(id) ON DELETE SET NULL,
  entity_type              activity_entity_type      NOT NULL,
  entity_id                UUID                      NOT NULL,
  offer_id                 UUID                      REFERENCES offers(id) ON DELETE SET NULL,
  metadata                 JSONB                     NOT NULL DEFAULT '{}'::jsonb,
  created_at               TIMESTAMPTZ               NOT NULL DEFAULT now(),
  CONSTRAINT activity_events_recipient_check CHECK (
    (
      recipient_scope = 'technician'
      AND recipient_technician_id IS NOT NULL
      AND recipient_company_id IS NULL
    )
    OR
    (
      recipient_scope = 'company'
      AND recipient_company_id IS NOT NULL
      AND recipient_technician_id IS NULL
    )
  )
);

CREATE TABLE activity_reads (
  activity_event_id UUID        NOT NULL REFERENCES activity_events(id) ON DELETE CASCADE,
  profile_id        UUID        NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  read_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (activity_event_id, profile_id)
);



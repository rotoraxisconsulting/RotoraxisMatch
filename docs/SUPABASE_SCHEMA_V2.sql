-- ============================================================
-- RotoraxisMatch V2 — Supabase/Postgres Schema
-- ============================================================
-- CLEAN-START POLICY:
--   Run this file on a fresh Supabase project.
--   It contains: enums, CREATE TABLE statements, catalog INSERTs
--   (technician_types, license_categories, aircraft_types,
--    company_types, contract_types).
--
--   It does NOT contain: local demo seed data.
--   Local demo JSON seeds (src/data/seeds/) use human-readable IDs
--   (tech-001, comp-001, etc.) that are NOT valid Supabase UUIDs.
--   Those seeds exist only for local AsyncStorage/demo mode and must
--   NOT be inserted into a Supabase database.
--
-- After running this file:
--   1. Create the first admin user in Supabase Auth.
--   2. Run docs/V2_S1_ADMIN_BOOTSTRAP_SQL.sql to insert the admin
--      profile row (profiles.id = auth.users.id).
--   3. Register real users via Supabase Auth — all IDs come from
--      auth.uid() and are generated by Postgres (gen_random_uuid()).
--
-- No destructive SQL included.
-- ============================================================


-- ============================================================
-- ENUMS
-- ============================================================
-- Using Postgres enums for all status fields.
-- Rationale: status values are fixed by business logic and change
-- only with deliberate migrations. Enums provide type safety and
-- clear documentation of allowed values.
-- Catalog values (technician types, license codes, etc.) are in
-- catalog tables instead so they can be extended without migrations.
-- ============================================================

CREATE TYPE app_role AS ENUM (
  'technician',
  'company_user',
  'admin'
);

CREATE TYPE user_status AS ENUM (
  'pending_verification',
  'active',
  'blocked',
  'suspended'
);

CREATE TYPE verification_status AS ENUM (
  'pending',
  'verified',
  'rejected'
);

CREATE TYPE document_status AS ENUM (
  'pending',
  'verified',
  'rejected',
  'expired'
);

CREATE TYPE offer_request_status AS ENUM (
  'pending',
  'accepted',
  'rejected',
  'expired',    -- set server-side when offer expires without a response
  'withdrawn'   -- voluntary cancellation by the initiating party
);

CREATE TYPE offer_status AS ENUM (
  'draft',
  'published',
  'closed',
  'expired'
);

CREATE TYPE company_member_role AS ENUM (
  'admin',
  'recruiter',
  'viewer'
);

CREATE TYPE experience_unit AS ENUM (
  'hours',
  'years'
);

CREATE TYPE sender_role AS ENUM (
  'technician',
  'company'
);

CREATE TYPE activity_type AS ENUM (
  'application_received',
  'application_accepted',
  'application_rejected',
  'direct_offer_received',
  'direct_offer_accepted',
  'direct_offer_rejected',
  'chat_message_received'
);

CREATE TYPE activity_recipient_scope AS ENUM (
  'technician',
  'company'
);

CREATE TYPE activity_entity_type AS ENUM (
  'offer_request',
  'offer_application',
  'chat_message'
);


